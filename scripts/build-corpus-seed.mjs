import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const alphabet = 'abcdefghijklmnopqrstuvwxyz';
const ordinal = Object.fromEntries(
  [...alphabet].map((letter, index) => [letter, index + 1])
);
const reverseOrdinal = Object.fromEntries(
  [...alphabet].map((letter, index) => [letter, 26 - index])
);

function valueFor(phrase, mappings) {
  const normalized = phrase
    .normalize('NFKD')
    .toLowerCase()
    .replace(/[\u0300-\u036f]/g, '');
  let total = 0;
  let cursor = 0;
  while (cursor < normalized.length) {
    const digits = normalized.slice(cursor).match(/^\d+/)?.[0];
    if (digits) {
      const value = Number(digits);
      if (!Number.isSafeInteger(value)) {
        throw new Error(`Numeric token is too large in phrase: ${phrase}`);
      }
      total += value;
      cursor += digits.length;
      continue;
    }
    total += mappings[normalized[cursor]] ?? 0;
    cursor += 1;
  }
  return total;
}

export function calculateCoreValues(phrase) {
  const ordinalValue = valueFor(phrase, ordinal);
  const reverseValue = valueFor(phrase, reverseOrdinal);
  const reduction = Object.fromEntries(
    Object.entries(ordinal).map(([letter, value]) => [
      letter,
      ((value - 1) % 9) + 1
    ])
  );
  const reverseReduction = Object.fromEntries(
    Object.entries(reverseOrdinal).map(([letter, value]) => [
      letter,
      ((value - 1) % 9) + 1
    ])
  );
  return {
    'english-ordinal': ordinalValue,
    'full-reduction': valueFor(phrase, reduction),
    'reverse-ordinal': reverseValue,
    'reverse-reduction': valueFor(phrase, reverseReduction)
  };
}

function sqlText(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function validateRows(input) {
  if (!Array.isArray(input)) throw new Error('Corpus input must be an array.');
  const seen = new Set();
  return input.map((row, index) => {
    if (!row || typeof row !== 'object' || Array.isArray(row)) {
      throw new Error(`Corpus row ${index + 1} must be an object.`);
    }
    const phrase = typeof row.phrase === 'string' ? row.phrase.trim() : '';
    if (!phrase || phrase.length > 500) {
      throw new Error(`Corpus row ${index + 1} has an invalid phrase.`);
    }
    const key = phrase.toLocaleLowerCase('en');
    if (seen.has(key)) throw new Error(`Duplicate corpus phrase: ${phrase}`);
    seen.add(key);
    return {
      phrase,
      category: row.category ? String(row.category) : null,
      source: row.source ? String(row.source) : null,
      metadata:
        row.metadata && typeof row.metadata === 'object'
          ? row.metadata
          : { seed: true }
    };
  });
}

export function buildSeedSql(input) {
  const rows = validateRows(input);
  const lines = [
    '-- Generated by scripts/build-corpus-seed.mjs. Do not edit manually.',
    'begin;',
    ''
  ];

  for (const row of rows) {
    const phrase = sqlText(row.phrase);
    const category = row.category === null ? 'null' : sqlText(row.category);
    const source = row.source === null ? 'null' : sqlText(row.source);
    const metadata = `${sqlText(JSON.stringify(row.metadata))}::jsonb`;
    lines.push(
      'insert into public.phrase_corpus (phrase, category, source, metadata, is_active)',
      `values (${phrase}, ${category}, ${source}, ${metadata}, true)`,
      'on conflict (phrase) do update set',
      '  category = excluded.category,',
      '  source = excluded.source,',
      '  metadata = excluded.metadata,',
      '  is_active = true;',
      ''
    );

    for (const [cipherId, value] of Object.entries(
      calculateCoreValues(row.phrase)
    )) {
      lines.push(
        'insert into public.phrase_cipher_values (phrase_id, cipher_id, value)',
        `select id, ${sqlText(cipherId)}, ${value}`,
        'from public.phrase_corpus',
        `where phrase = ${phrase}`,
        'on conflict (phrase_id, cipher_id) do update',
        'set value = excluded.value;',
        ''
      );
    }
  }

  lines.push('commit;', '');
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const args = process.argv
    .slice(2)
    .filter((argument) => argument !== '--check');
  const [inputPath, outputPath] = args;
  if (!inputPath || !outputPath) {
    throw new Error(
      'Usage: node scripts/build-corpus-seed.mjs <input.json> <output.sql> [--check]'
    );
  }
  const input = JSON.parse(readFileSync(inputPath, 'utf8'));
  const sql = buildSeedSql(input);
  if (check) {
    const existing = readFileSync(outputPath, 'utf8');
    if (existing !== sql) {
      throw new Error(
        `${outputPath} is out of date. Run npm run corpus:build.`
      );
    }
    return;
  }
  writeFileSync(outputPath, sql);
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main();
}
